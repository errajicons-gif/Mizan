export function resolveRecipeAssetImage(recipe: Recipe): string {
  if (RECIPE_ASSET_POOL[recipe.id]) {
    return RECIPE_ASSET_POOL[recipe.id];
  }
  if (recipe.imageUrl) {
    return recipe.imageUrl;
  }
  if (recipe.mealSlots.includes('breakfast')) return IMG_BREAKFAST_BELDI;
  if (recipe.tags.includes('snack')) return IMG_OATS_SNACKS;
  if (recipe.tags.includes('vegetarian')) return IMG_ZAALOUK_TAKTOUKA;
  return IMG_HERO_TABLE;
}

